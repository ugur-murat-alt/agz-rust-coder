//! Real-Cargo integration tests for `repair(action=minimize)`.
//!
//! Every fixture builds a temporary Cargo project with irrelevant modules,
//! introduces a failure through a normal `change` stage, records fresh FAIL
//! evidence, and then drives minimization while asserting that the original
//! workspace bytes never change and that the proof package reproduces in a
//! clean temporary directory.

use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
    sync::Arc,
    time::{SystemTime, UNIX_EPOCH},
};

use agz_rust_mcp::{
    Config,
    change::{ChangeAction, ChangeOutcome, ChangeRequest, ChangeService, PatchInput},
    gate::{GateDetail, GateTargetId, ValidationOptions},
    process::ProcessSupervisor,
    repair::{RepairAction, RepairBudget, RepairReductionScope, RepairRequest, RepairService},
    workspace::{ClientRoots, RootGuard, WorkspaceRoot},
};
use sha2::{Digest, Sha256};
use tokio_util::sync::CancellationToken;

const MODULES: &[&str] = &["alpha", "beta", "gamma", "delta", "epsilon", "zeta"];

struct Fixture {
    root: PathBuf,
    config: Config,
    guard: Arc<RootGuard>,
    change: Arc<ChangeService>,
    unused_impl: bool,
}

impl Fixture {
    fn new(label: &str, unused_impl: bool) -> Self {
        let stamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_or(0, |duration| duration.as_nanos());
        let base = fs::canonicalize(std::env::temp_dir())
            .expect("canonical temp directory")
            .join(format!(
                "agz-minimize-{label}-{}-{stamp}",
                std::process::id()
            ));
        let root = base.join("workspace");
        let state = base.join("state");
        fs::create_dir_all(root.join("src")).expect("create project source directory");
        fs::create_dir_all(&state).expect("create state directory");
        fs::write(
            root.join("Cargo.toml"),
            "[package]\nname = \"minimize-fixture\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[workspace]\n",
        )
        .expect("write manifest");
        fs::write(
            root.join("Cargo.lock"),
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"minimize-fixture\"\nversion = \"0.1.0\"\n",
        )
        .expect("write lockfile");
        fs::write(root.join("src/lib.rs"), lib_source(unused_impl)).expect("write source");
        for name in MODULES {
            fs::write(
                root.join(format!("src/{name}.rs")),
                format!(
                    "pub fn {name}_unused() -> usize {{\n    {}\n}}\n",
                    name.len()
                ),
            )
            .expect("write module source");
        }
        let mut config = Config::defaults_at(&root);
        config.gate.debounce_ms = 10;
        config.gate.hard_timeout_ms = 120_000;
        config.gate.cache_dir = state.join("gate-cache");
        config.gate.lease_dir = state.join("leases");
        config.change.scratch_dir = state.join("change");
        config.telemetry.enabled = false;
        config.telemetry.path = state.join("activity.jsonl");
        let guard = Arc::new(
            RootGuard::new([root.clone()], std::iter::empty()).expect("create root guard"),
        );
        let change = Arc::new(
            ChangeService::new(
                config.clone(),
                Arc::clone(&guard),
                ProcessSupervisor::without_journal(),
            )
            .expect("create change service"),
        );
        Self {
            root,
            config,
            guard,
            change,
            unused_impl,
        }
    }

    fn workspace(&self) -> WorkspaceRoot {
        self.guard
            .snapshot(ClientRoots::unsupported())
            .expect("root snapshot")
            .select(Some(&self.root))
            .expect("select workspace")
    }

    async fn change(&self, request: ChangeRequest) -> ChangeOutcome {
        self.change
            .execute(request, &self.workspace(), CancellationToken::new(), None)
            .await
    }

    async fn park_failure(&self) -> (String, String) {
        let created = self.change(create_request()).await;
        assert_eq!(created.status, "CREATED", "{created:#?}");
        let id = created.data.change_id.clone().expect("change id");
        let base = created.data.base_identity.clone().expect("base identity");
        let stage_patch = if self.unused_impl {
            patch(
                "src/lib.rs",
                "    let counter = Counter::new();\n    let base = counter.value;\n    base + text.len()",
                "    let counter = Counter::new();\n    let base = counter.value;\n    let moved = consume(text);\n    base + moved + text.len()",
            )
        } else {
            patch(
                "src/lib.rs",
                "    let base = 1;\n    base + text.len()",
                "    let base = 1;\n    let moved = consume(text);\n    base + moved + text.len()",
            )
        };
        let staged = self
            .change(stage_request(&id, 0, &base, vec![stage_patch]))
            .await;
        assert_eq!(staged.status, "STAGED", "{staged:#?}");
        let failed = self
            .change(validate_request(&id, 1, &base, GateTargetId::Check))
            .await;
        assert_eq!(failed.status, "FAIL", "{failed:#?}");
        (id, base)
    }

    async fn minimize(
        &self,
        id: &str,
        scope: RepairReductionScope,
        budget: RepairBudget,
    ) -> agz_rust_mcp::repair::RepairOutcome {
        let request = RepairRequest {
            action: RepairAction::Minimize,
            change_id: id.to_owned(),
            diagnostic_ids: Vec::new(),
            candidates: Vec::new(),
            test_target: None,
            budget,
            reduction_scope: scope,
            failure_predicate: None,
        };
        RepairService::new(self.config.clone(), Arc::clone(&self.change))
            .execute(request, &self.workspace(), CancellationToken::new(), None)
            .await
    }

    fn cleanup_verified(&self) {
        let directory = self.change.scratch_root().join("minimize");
        let entries = fs::read_dir(&directory).map_or(0, Iterator::count);
        assert_eq!(entries, 0, "minimize scratch must be cleaned up");
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        if let Some(base) = self.root.parent() {
            let _ = fs::remove_dir_all(base);
        }
    }
}

fn lib_source(unused_impl: bool) -> String {
    let mut modules = String::new();
    for name in MODULES {
        modules.push_str(&format!("mod {name};\n"));
    }
    let body = if unused_impl {
        "    let counter = Counter::new();\n    let base = counter.value;\n    base + text.len()"
    } else {
        "    let base = 1;\n    base + text.len()"
    };
    let counter = if unused_impl {
        "\npub struct Counter {\n    pub value: usize,\n}\n\nimpl Counter {\n    pub fn new() -> Self {\n        Self { value: 0 }\n    }\n}\n"
    } else {
        ""
    };
    format!(
        "{modules}\npub fn consume(value: String) -> usize {{\n    value.len()\n}}\n{counter}\npub fn run() -> usize {{\n    let text = String::from(\"x\");\n{body}\n}}\n"
    )
}

fn create_request() -> ChangeRequest {
    ChangeRequest {
        action: ChangeAction::Create,
        change_id: None,
        expected_revision: None,
        base_identity: None,
        patches: Vec::new(),
        new_files: Vec::new(),
        migration: None,
        target: GateTargetId::Check,
        options: ValidationOptions::default(),
        detail: GateDetail::Compact,
        timings: false,
    }
}

fn stage_request(id: &str, revision: u64, base: &str, patches: Vec<PatchInput>) -> ChangeRequest {
    ChangeRequest {
        action: ChangeAction::Stage,
        change_id: Some(id.to_owned()),
        expected_revision: Some(revision),
        base_identity: Some(base.to_owned()),
        patches,
        new_files: Vec::new(),
        migration: None,
        target: GateTargetId::Check,
        options: ValidationOptions::default(),
        detail: GateDetail::Compact,
        timings: false,
    }
}

fn validate_request(id: &str, revision: u64, base: &str, target: GateTargetId) -> ChangeRequest {
    ChangeRequest {
        action: ChangeAction::Validate,
        change_id: Some(id.to_owned()),
        expected_revision: Some(revision),
        base_identity: Some(base.to_owned()),
        patches: Vec::new(),
        new_files: Vec::new(),
        migration: None,
        target,
        options: ValidationOptions::default(),
        detail: GateDetail::Compact,
        timings: false,
    }
}

fn patch(file: &str, old: &str, new: &str) -> PatchInput {
    PatchInput {
        file: file.to_owned(),
        old_string: old.to_owned(),
        new_string: new.to_owned(),
    }
}

fn digest(path: &Path) -> String {
    let bytes = fs::read(path).expect("read digest target");
    let mut hasher = Sha256::new();
    hasher.update(&bytes);
    format!("{:x}", hasher.finalize())
}

fn full_budget() -> RepairBudget {
    RepairBudget {
        max_candidates: 32,
        max_compiles: 16,
        wall_time_ms: 120_000,
    }
}

#[tokio::test]
#[allow(clippy::too_many_lines)]
async fn large_fixture_is_minimized_and_the_proof_package_reproduces_in_a_clean_directory() {
    let fixture = Fixture::new("proof", false);
    let (id, _base) = fixture.park_failure().await;
    let lib_before = digest(&fixture.root.join("src/lib.rs"));
    let module_before = digest(&fixture.root.join("src/alpha.rs"));

    let outcome = fixture
        .minimize(&id, RepairReductionScope::default(), full_budget())
        .await;
    assert_eq!(outcome.status, "REPRODUCED", "{outcome:#?}");
    assert!(!outcome.is_error);
    assert!(outcome.data.usable);
    assert!(outcome.data.reproduced);
    assert_eq!(outcome.data.verification, "exportVerified");
    let proof = outcome.data.proof.as_ref().expect("proof package");
    assert!(proof.export_verified, "{proof:#?}");
    assert!(proof.package_complete, "{proof:#?}");
    assert_eq!(proof.target, "check");
    assert!(proof.lockfile_preserved);
    assert!(proof.reproduction_command.starts_with("cargo "));
    assert!(
        proof
            .files
            .iter()
            .any(|file| file.file == "src/lib.rs" && file.content.is_some()),
        "{proof:#?}"
    );
    assert!(
        !proof.files.iter().any(|file| file.file == "src/alpha.rs"),
        "irrelevant module file must not survive minimization: {proof:#?}"
    );
    assert!(
        proof.files_total <= 3,
        "only Cargo.toml, Cargo.lock, and src/lib.rs should remain: {proof:#?}"
    );
    let lib = proof
        .files
        .iter()
        .find(|file| file.file == "src/lib.rs")
        .and_then(|file| file.content.as_deref())
        .expect("minimized lib source");
    assert!(!lib.contains("mod alpha;"), "{lib}");
    assert!(lib.contains("borrow") || lib.contains("consume"), "{lib}");

    // Every accepted reduction carries its failure match and selection reason.
    let accepted: Vec<_> = outcome
        .data
        .reductions
        .iter()
        .filter(|reduction| reduction.status == "accepted")
        .collect();
    assert!(!accepted.is_empty(), "{:#?}", outcome.data.reductions);
    assert!(
        accepted
            .iter()
            .all(|reduction| reduction.failure_match == "matched"
                && reduction.reason.contains("selected")),
        "{accepted:#?}"
    );
    assert!(outcome.data.reductions_total > 0);

    // Independent reproduction: write only the returned package into a clean
    // directory and run Cargo there.
    let export = fixture
        .root
        .parent()
        .expect("fixture base")
        .join("clean-export");
    fs::create_dir_all(&export).expect("create clean export directory");
    for file in &proof.files {
        let path = export.join(&file.file);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).expect("create export parent");
        }
        fs::write(&path, file.content.as_deref().unwrap_or_default()).expect("write export file");
    }
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_owned());
    let output = Command::new(cargo)
        .args(["check", "--offline"])
        .current_dir(&export)
        .env("CARGO_TARGET_DIR", export.join("target"))
        .output()
        .expect("run clean export check");
    assert!(
        !output.status.success(),
        "the exported package must still fail: {output:?}"
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("E0382") && stderr.contains("borrow of moved value: `text`"),
        "clean export must reproduce the exact target diagnostic: {stderr}"
    );
    let predicate = outcome.data.predicate.as_ref().expect("predicate");
    assert_eq!(predicate.code, "E0382");
    assert!(predicate.message.contains("borrow of moved value: `text`"));
    assert!(predicate.message_tokens.iter().any(|token| token == "text"));

    // Original worktree sources stay byte-identical and no build directory is
    // created inside it.
    assert_eq!(digest(&fixture.root.join("src/lib.rs")), lib_before);
    assert_eq!(digest(&fixture.root.join("src/alpha.rs")), module_before);
    assert!(!fixture.root.join("target").exists());
    fixture.cleanup_verified();
}

#[tokio::test]
async fn budget_stop_publishes_best_known_reproducer_with_remaining_scope() {
    // The unused impl block poisons type-checking when removed, so the bulk
    // trial is rejected with `codeAbsent` instead of the E0382 predicate. That
    // rejection must be recorded, and the candidate budget must stop the search
    // visibly as BEST_KNOWN_REPRODUCER.
    let fixture = Fixture::new("budget", true);
    let (id, _base) = fixture.park_failure().await;
    let outcome = fixture
        .minimize(
            &id,
            RepairReductionScope::default(),
            RepairBudget {
                max_candidates: 2,
                max_compiles: 16,
                wall_time_ms: 120_000,
            },
        )
        .await;
    assert_eq!(outcome.status, "BEST_KNOWN_REPRODUCER", "{outcome:#?}");
    assert!(!outcome.is_error);
    assert!(outcome.data.usable);
    assert!(!outcome.data.reproduced);
    assert_eq!(outcome.data.verification, "trialVerified");
    assert_eq!(outcome.data.stop_reason, "maxCandidates");
    let proof = outcome.data.proof.as_ref().expect("proof package");
    assert!(!proof.export_verified);
    assert!(
        outcome
            .data
            .remaining_risks
            .iter()
            .any(|risk| risk.contains("not claimed")
                || risk.contains("unsearched")
                || risk.contains("budget")),
        "{:#?}",
        outcome.data.remaining_risks
    );
    let budget = outcome.data.budget.as_ref().expect("budget data");
    assert!(budget.compiles_used <= 4, "{budget:#?}");
    assert_eq!(budget.candidates_used, 2);
    assert!(
        outcome
            .data
            .reductions
            .iter()
            .any(|reduction| reduction.status == "rejected"
                && reduction.failure_match == "codeAbsent"
                && reduction.reason.starts_with("not selected:")),
        "{:#?}",
        outcome.data.reductions
    );
    fixture.cleanup_verified();
}

#[tokio::test]
async fn unavailable_cargo_is_never_reported_as_reproduced() {
    let fixture = Fixture::new("offline", false);
    let (id, _base) = fixture.park_failure().await;
    let mut config = fixture.config.clone();
    config.cargo.path = Some(fixture.root.join("missing-cargo-binary"));
    let request = RepairRequest {
        action: RepairAction::Minimize,
        change_id: id,
        diagnostic_ids: Vec::new(),
        candidates: Vec::new(),
        test_target: None,
        budget: full_budget(),
        reduction_scope: RepairReductionScope::default(),
        failure_predicate: None,
    };
    let outcome = RepairService::new(config, Arc::clone(&fixture.change))
        .execute(
            request,
            &fixture.workspace(),
            CancellationToken::new(),
            None,
        )
        .await;
    assert_eq!(outcome.status, "NOT_REPRODUCED", "{outcome:#?}");
    assert!(!outcome.data.usable);
    assert!(!outcome.data.reproduced);
    assert!(outcome.data.proof.is_none());
    assert_eq!(outcome.data.stop_reason, "initialInconclusive");
    assert!(
        outcome.data.reason.to_lowercase().contains("unavailable"),
        "{}",
        outcome.data.reason
    );
    fixture.cleanup_verified();
}

#[tokio::test]
async fn cancelled_minimize_publishes_no_reproducer() {
    let fixture = Fixture::new("cancel", false);
    let (id, _base) = fixture.park_failure().await;
    let cancellation = CancellationToken::new();
    cancellation.cancel();
    let request = RepairRequest {
        action: RepairAction::Minimize,
        change_id: id,
        diagnostic_ids: Vec::new(),
        candidates: Vec::new(),
        test_target: None,
        budget: full_budget(),
        reduction_scope: RepairReductionScope::default(),
        failure_predicate: None,
    };
    let outcome = RepairService::new(fixture.config.clone(), Arc::clone(&fixture.change))
        .execute(request, &fixture.workspace(), cancellation, None)
        .await;
    assert_eq!(outcome.status, "CANCELLED", "{outcome:#?}");
    assert!(outcome.is_error);
    assert!(!outcome.data.usable);
    assert!(outcome.data.proof.is_none());
    assert_eq!(outcome.data.stop_reason, "cancelled");
    assert!(outcome.data.reductions.is_empty());
}

#[tokio::test]
async fn item_scope_never_touches_module_declarations() {
    let fixture = Fixture::new("scope", false);
    let (id, _base) = fixture.park_failure().await;
    let outcome = fixture
        .minimize(&id, RepairReductionScope::Items, full_budget())
        .await;
    assert_eq!(outcome.status, "REPRODUCED", "{outcome:#?}");
    let proof = outcome.data.proof.as_ref().expect("proof package");
    assert!(
        proof.files.iter().any(|file| file.file == "src/alpha.rs"),
        "items scope must not delete module files: {proof:#?}"
    );
    fixture.cleanup_verified();
}
