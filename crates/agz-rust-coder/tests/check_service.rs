#[tokio::test]
async fn cancellation_detaches_the_last_subscriber_and_cleans_the_job() {
    let project = TestProject::new(
        "cancel",
        "pub fn value() -> usize { 1 }\n",
        Some("fn main() { std::thread::sleep(std::time::Duration::from_secs(5)); }\n"),
    );
    let service = project.service();
    let cancellation = tokio_util::sync::CancellationToken::new();
    let running = {
        let service = Arc::clone(&service);
        let root = project.root.clone();
        let cancellation = cancellation.clone();
        tokio::spawn(async move {
            service
                .run(
                    GateRequest::new(root, GateTargetId::Check),
                    None,
                    Some(cancellation),
                )
                .await
        })
    };
    for _ in 0..200 {
        if service.active_count() > 0 {
            break;
        }
        tokio::time::sleep(Duration::from_millis(5)).await;
    }
    assert!(service.active_count() > 0, "check job never became active");
    cancellation.cancel();
    let evidence = running.await.expect("join cancelled check");
    assert_eq!(evidence.status, GateStatus::Cancelled);
    for _ in 0..200 {
        if service.active_count() == 0 {
            break;
        }
        tokio::time::sleep(Duration::from_millis(5)).await;
    }
    assert_eq!(service.active_count(), 0);
    service.close().await;
}

