use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
    sync::{Arc, Mutex},
    time::{Duration, SystemTime, UNIX_EPOCH},
};

use agz_rust_coder::{
    Config,
    config::GateScope as ConfigGateScope,
    gate::{GateAuthority, GateRequest, GateScopeStrategy, GateStatus, GateTargetId},
    tools::CheckService,
    workspace::RootGuard,
};

struct TestProject {
    root: PathBuf,
    state: PathBuf,
}

impl TestProject {
    fn new(label: &str, source: &str, build_script: Option<&str>) -> Self {
        let stamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_or(0, |duration| duration.as_nanos());
        let base = fs::canonicalize(std::env::temp_dir())
            .expect("canonical temp directory")
            .join(format!(
                "agz-rust-coder-check-{label}-{}-{stamp}",
                std::process::id()
            ));
        let root = base.join("workspace");
        let state = base.join("state");
        fs::create_dir_all(root.join("src")).expect("create project source directory");
        fs::create_dir_all(&state).expect("create project state directory");
        fs::write(
            root.join("Cargo.toml"),
            "[package]\nname = \"check-fixture\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[workspace]\n",
        )
        .expect("write manifest");
        fs::write(
            root.join("Cargo.lock"),
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"check-fixture\"\nversion = \"0.1.0\"\n",
        )
        .expect("write lockfile");
        fs::write(root.join("src/lib.rs"), source).expect("write source");
        if let Some(build_script) = build_script {
            fs::write(root.join("build.rs"), build_script).expect("write build script");
        }
        git(&root, &["init", "--quiet"]);
        git(&root, &["config", "user.email", "check@example.invalid"]);
        git(&root, &["config", "user.name", "Check Fixture"]);
        git(&root, &["add", "."]);
        git(&root, &["commit", "--quiet", "-m", "fixture"]);
        Self { root, state }
    }

    fn service(&self) -> Arc<CheckService> {
        self.service_with_scope(ConfigGateScope::Shadow)
    }

    fn service_with_scope(&self, scope: ConfigGateScope) -> Arc<CheckService> {
        let mut config = Config::defaults_at(&self.root);
        config.gate.debounce_ms = 10;
        config.gate.hard_timeout_ms = 60_000;
        config.gate.cache_dir = self.state.join("cache");
        config.gate.lease_dir = self.state.join("leases");
        config.gate.scope = scope;
        let guard = Arc::new(
            RootGuard::new([self.root.clone()], std::iter::empty()).expect("create root guard"),
        );
        Arc::new(CheckService::new(config, guard))
    }

    fn service_with_cargo(&self, cargo: PathBuf) -> Arc<CheckService> {
        let mut config = Config::defaults_at(&self.root);
        config.gate.debounce_ms = 10;
        config.gate.hard_timeout_ms = 60_000;
        config.gate.cache_dir = self.state.join("cache");
        config.gate.lease_dir = self.state.join("leases");
        config.cargo.path = Some(cargo);
        let guard = Arc::new(
            RootGuard::new([self.root.clone()], std::iter::empty()).expect("create root guard"),
        );
        Arc::new(CheckService::new(config, guard))
    }
}

#[tokio::test]
async fn check_scope_applies_workspace_shadow_and_affected_contracts() {
    let project = TestProject::new("scope", "pub fn value() -> usize { 1 }\n", None);
    let affected = project.service_with_scope(ConfigGateScope::Affected);

    let clean = affected
        .run(
            GateRequest::new(&project.root, GateTargetId::Check),
            None,
            None,
        )
        .await;
    assert_eq!(clean.scope.strategy, GateScopeStrategy::Workspace);
    assert!(
        clean
            .scope
            .widened_because
            .iter()
            .any(|reason| reason.contains("empty"))
    );
    assert!(clean.steps[0].command.contains(&"--workspace".to_owned()));

    fs::write(
        project.root.join("src/lib.rs"),
        "pub fn value() -> usize { 2 }\n",
    )
    .expect("modify owned package source");
    let narrowed = affected
        .run(
            GateRequest::new(&project.root, GateTargetId::Check),
            None,
            None,
        )
        .await;
    assert_eq!(narrowed.scope.strategy, GateScopeStrategy::Affected);
    assert_eq!(narrowed.scope.packages, ["check-fixture"]);
    assert!(narrowed.steps[0].command.contains(&"-p".to_owned()));
    assert!(
        narrowed.steps[0]
            .command
            .contains(&"check-fixture".to_owned())
    );
    affected.close().await;

    let shadow = project.service_with_scope(ConfigGateScope::Shadow);
    let measured = shadow
        .run(
            GateRequest::new(&project.root, GateTargetId::Check),
            None,
            None,
        )
        .await;
    assert_eq!(measured.scope.strategy, GateScopeStrategy::Shadow);
    assert_eq!(measured.scope.packages, ["check-fixture"]);
    assert!(
        measured.steps[0]
            .command
            .contains(&"--workspace".to_owned())
    );
    shadow.close().await;
}

