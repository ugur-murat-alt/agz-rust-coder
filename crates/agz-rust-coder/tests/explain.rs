#[tokio::test]
async fn cargo_fixture_keeps_macro_expansion_and_trait_evidence() {
    let project = TestProject::new("cargo");
    let evidence = project
        .service()
        .run(
            GateRequest::new(project.root(), GateTargetId::Check),
            None,
            None,
        )
        .await;
    assert_eq!(evidence.status, GateStatus::Fail, "{evidence:#?}");
    let diagnostics = evidence
        .steps
        .iter()
        .flat_map(|step| step.diagnostics.iter().cloned())
        .collect::<Vec<GateDiagnostic>>();
    assert!(!diagnostics.is_empty());

    // Nested declarative macro: rustc expansion provenance survives the gate
    // conversion and is presented as observed compiler evidence.
    let macro_diagnostics =
        explain::select_diagnostics(&diagnostics, "src/lib.rs", None, Some("E0308"));
    let view = explain::macro_compiler_view(&macro_diagnostics);
    let expansion = view
        .fragments
        .iter()
        .find(|fragment| {
            fragment.kind == "macroExpansion"
                && fragment.provenance == ExplainProvenance::ObservedCompiler
        })
        .expect("rustc expansion provenance");
    assert!(expansion.detail.contains("inner"), "{}", expansion.detail);
    assert!(view.macro_depth >= 1);

    // Missing trait bound with a related impl/where clause from bounded source.
    let source = fs::read_to_string(project.root().join("src/lib.rs")).expect("read source");
    let hint = explain::trait_hint(&macro_diagnostics).or_else(|| {
        let all = explain::select_diagnostics(&diagnostics, "lib.rs", None, None);
        explain::trait_hint(&all)
    });
    assert_eq!(hint.as_deref(), Some("Debug"), "{hint:?}");
    let trait_source = explain::select_diagnostics(&diagnostics, "lib.rs", None, None);
    let view = explain::trait_compiler_view(
        &trait_source,
        "src/lib.rs",
        1,
        Some(&source),
        hint.as_deref(),
    );
    assert!(view.fragments.iter().any(|fragment| {
        fragment.kind == "failedBound" && fragment.provenance == ExplainProvenance::ObservedCompiler
    }));
    assert!(
        view.fragments.iter().any(|fragment| {
            fragment.kind == "expectedFound" && fragment.detail.contains("i32")
        })
    );
    assert!(view.fragments.iter().any(|fragment| {
        matches!(fragment.kind.as_str(), "candidateImpl" | "whereClause")
            && fragment.provenance == ExplainProvenance::Inferred
            && fragment.source.is_some()
    }));
}

#[tokio::test]
async fn cfg_enablement_uses_recorded_cargo_features() {
    let project = TestProject::new("cfg");
    let load = project.metadata_load();
    let anchor = explain::anchor_feature_maps(
        &load.snapshot.metadata,
        project.root(),
        Path::new("src/lib.rs"),
    );
    assert_eq!(anchor.package.as_deref(), Some("explain-fixture"));
    assert!(anchor.declared.contains_key("extra"));
    assert!(!anchor.recorded.contains("extra"));
    let declared = anchor.declared.clone();
    let recorded = anchor.recorded.clone();

    let source = "#[cfg(feature = \"extra\")]\npub fn feature_gated() {}\n";
    let features = feature_selection(recorded.clone(), &declared, &[], false, false);
    let view = explain::cfg_view("src/lib.rs", 2, source, &features, None);
    assert!(view.fragments.iter().any(|fragment| {
        fragment.kind == "cfgCondition"
            && fragment.provenance == ExplainProvenance::Inferred
            && fragment.detail.contains("disables")
    }));

    // Requested features are an inference over the declared map, never a
    // verified compile result.
    let requested = feature_selection(recorded, &declared, &["extra".to_owned()], false, false);
    let view = explain::cfg_view("src/lib.rs", 2, source, &requested, None);
    assert!(view.fragments.iter().any(|fragment| {
        fragment.kind == "cfgCondition"
            && fragment.provenance == ExplainProvenance::Inferred
            && fragment.detail.contains("enables")
    }));
    assert!(
        features.note.contains("not compiler-verified")
            || features
                .note
                .contains("target/compiler predicates stay unknown")
    );
}

#[tokio::test]
async fn feature_evidence_is_scoped_to_the_anchor_package() {
    let project = multi_crate_project("multi-crate");
    let load = project.metadata_load();
    let app = explain::anchor_feature_maps(
        &load.snapshot.metadata,
        project.root(),
        Path::new("app/src/lib.rs"),
    );
    assert_eq!(app.package.as_deref(), Some("explain-app"));
    assert!(app.declared.contains_key("app-extra"));
    assert!(!app.declared.contains_key("dep-only"));
    assert!(!app.recorded.contains("dep-only"), "{:?}", app.recorded);

    // A feature activated only for the dependency must not enable the cfg in
    // the workspace member that owns the anchor.
    let source = "#[cfg(feature = \"dep-only\")]\npub fn gated_by_dependency() {}\n";
    let features = feature_selection(app.recorded.clone(), &app.declared, &[], false, false);
    let view = explain::cfg_view("app/src/lib.rs", 2, source, &features, None);
    assert!(view.fragments.iter().any(|fragment| {
        fragment.kind == "cfgCondition"
            && fragment.provenance == ExplainProvenance::Inferred
            && fragment.detail.contains("disables")
    }));

    // Requesting a dependency-only feature for the app package is not a
    // declared feature there, so enablement stays unknown instead of enabled.
    let features = feature_selection(
        app.recorded.clone(),
        &app.declared,
        &["dep-only".to_owned()],
        false,
        false,
    );
    let view = explain::cfg_view("app/src/lib.rs", 2, source, &features, None);
    assert!(view.fragments.iter().any(|fragment| {
        fragment.kind == "cfgCondition"
            && fragment.provenance == ExplainProvenance::Unknown
            && fragment.detail.contains("dep-only")
    }));

    // The dependency crate itself is compiled with its activated feature.
    let dep = explain::anchor_feature_maps(
        &load.snapshot.metadata,
        project.root(),
        Path::new("dep/src/lib.rs"),
    );
    assert_eq!(dep.package.as_deref(), Some("explain-dep"));
    assert!(dep.declared.contains_key("dep-only"));
    assert!(dep.recorded.contains("dep-only"), "{:?}", dep.recorded);
    let features = feature_selection(dep.recorded.clone(), &dep.declared, &[], false, false);
    let view = explain::cfg_view("dep/src/lib.rs", 2, source, &features, None);
    assert!(view.fragments.iter().any(|fragment| {
        fragment.kind == "cfgCondition"
            && fragment.provenance == ExplainProvenance::Inferred
            && fragment.detail.contains("enables")
    }));
}

#[tokio::test]
async fn derive_and_proc_macro_fixture_keeps_expansion_provenance() {
    let project = proc_macro_project("proc-macro");
    let evidence = project
        .service()
        .run(
            GateRequest::new(project.root(), GateTargetId::Check),
            None,
            None,
        )
        .await;
    assert_eq!(evidence.status, GateStatus::Fail, "{evidence:#?}");
    let diagnostics = evidence
        .steps
        .iter()
        .flat_map(|step| step.diagnostics.iter().cloned())
        .collect::<Vec<GateDiagnostic>>();
    let selected = explain::select_diagnostics(&diagnostics, "app/src/lib.rs", None, None);
    let view = explain::macro_compiler_view(&selected);
    let details = view
        .fragments
        .iter()
        .filter(|fragment| {
            fragment.kind == "macroExpansion"
                && fragment.provenance == ExplainProvenance::ObservedCompiler
        })
        .map(|fragment| fragment.detail.as_str())
        .collect::<Vec<_>>();

    // Built-in derives and custom proc-macro derives both surface through the
    // compiler's retained expansion provenance.
    assert!(
        details
            .iter()
            .any(|detail| detail.contains("derive(Clone)")),
        "{details:?}"
    );
    assert!(
        details.iter().any(|detail| detail.contains("ExplainGuard")),
        "{details:?}"
    );
    assert!(view.macro_depth >= 1);

    // Trait explanations keep the same compiler-retained expansion depth.
    let trait_diagnostics =
        explain::select_diagnostics(&diagnostics, "app/src/lib.rs", None, Some("E0277"));
    let trait_view =
        explain::trait_compiler_view(&trait_diagnostics, "app/src/lib.rs", 5, None, Some("Clone"));
    assert!(trait_view.macro_depth >= 1, "{trait_view:#?}");
}

#[test]
fn source_hash_binds_explanations_and_bounds_are_enforced() {
    let first = explain::source_sha256(b"pub fn a() {}\n");
    let second = explain::source_sha256(b"pub fn b() {}\n");
    assert_eq!(first.len(), 64);
    assert_eq!(first, explain::source_sha256(b"pub fn a() {}\n"));
    assert_ne!(first, second);

    let diagnostics = (0..MAX_DIAGNOSTICS + 4)
        .map(|index| diagnostic(index as u64))
        .collect::<Vec<_>>();
    let references = diagnostics.iter().collect::<Vec<_>>();
    let view = explain::macro_compiler_view(&references);
    assert_eq!(view.shown, MAX_DIAGNOSTICS);
    assert!(view.truncated);
}

