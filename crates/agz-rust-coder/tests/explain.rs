fn compiler_authority_stays_visible_in_advisory_conflicts() {
    let conflicts = explain::obligation_conflicts(true, &Default::default(), None);
    assert_eq!(conflicts.len(), 1);
    assert!(conflicts[0].compiler.contains("authoritative"));
    assert!(conflicts[0].analyzer.contains("no failed obligations"));
}

fn diagnostic(index: u64) -> GateDiagnostic {
    GateDiagnostic {
        code: Some("E0308".to_owned()),
        level: "error".to_owned(),
        file: Some("src/lib.rs".to_owned()),
        line: Some(index),
        message: "mismatched types".to_owned(),
        rendered: None,
        spans: vec![agz_rust_coder::gate::DiagnosticSpan {
            file: "src/lib.rs".to_owned(),
            byte_start: None,
            byte_end: None,
            line_start: index,
            line_end: index,
            column_start: 1,
            column_end: 2,
            is_primary: true,
            label: None,
            suggested_replacement: None,
            suggestion_applicability: None,
            expansion: None,
        }],
        children: Vec::new(),
        suggestions: Vec::new(),
    }
}
