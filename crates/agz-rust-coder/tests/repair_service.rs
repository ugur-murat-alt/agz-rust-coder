//! Real-Cargo integration tests for the compiler-driven `repair` tool.
//!
//! Every fixture builds a temporary Cargo project, introduces a failure with a
//! normal `change` stage, records fresh FAIL evidence through `change`
//! validate, and then drives `repair` analyze/try/compare while asserting that
//! the original workspace bytes never change.

use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
    sync::Arc,
    time::{SystemTime, UNIX_EPOCH},
};

use agz_rust_coder::{
    Config,
    change::{ChangeAction, ChangeOutcome, ChangeRequest, ChangeService, PatchInput},
    gate::{GateDetail, GateTargetId, ValidationOptions},
    process::ProcessSupervisor,
    repair::{
        RepairAction, RepairBudget, RepairBudgetInput, RepairCandidateInput, RepairReductionScope,
        RepairRequest, RepairService,
    },
    workspace::{ClientRoots, RootGuard, WorkspaceRoot},
};
use sha2::{Digest, Sha256};
use tokio_util::sync::CancellationToken;

struct Fixture {
    root: PathBuf,
    config: Config,
    guard: Arc<RootGuard>,
    change: Arc<ChangeService>,
}

impl Fixture {
    fn new(label: &str, source: &[u8]) -> Self {
        let stamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_or(0, |duration| duration.as_nanos());
        let base = fs::canonicalize(std::env::temp_dir())
            .expect("canonical temp directory")
            .join(format!("agz-repair-{label}-{}-{stamp}", std::process::id()));
        let root = base.join("workspace");
        let state = base.join("state");
        fs::create_dir_all(root.join("src")).expect("create project source directory");
        fs::create_dir_all(&state).expect("create state directory");
        fs::write(
            root.join("Cargo.toml"),
            "[package]\nname = \"repair-fixture\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[workspace]\n",
        )
        .expect("write manifest");
        fs::write(
            root.join("Cargo.lock"),
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"repair-fixture\"\nversion = \"0.1.0\"\n",
        )
        .expect("write lockfile");
        fs::write(root.join("src/lib.rs"), source).expect("write source");
        let mut config = Config::defaults_at(&root);
        config.gate.debounce_ms = 10;
        config.gate.hard_timeout_ms = 120_000;
        config.gate.cache_dir = state.join("gate-cache");
        config.gate.lease_dir = state.join("leases");
        config.change.scratch_dir = state.join("change");
        config.telemetry.enabled = false;
        config.telemetry.path = state.join("activity.jsonl");
        let guard = Arc::new(
            RootGuard::new([root.clone()], std::iter::empty()).expect("create root guard"),
        );
        let change = Arc::new(
            ChangeService::new(
                config.clone(),
                Arc::clone(&guard),
                ProcessSupervisor::without_journal(),
            )
            .expect("create change service"),
        );
        Self {
            root,
            config,
            guard,
            change,
        }
    }

    fn workspace(&self) -> WorkspaceRoot {
        self.guard
            .snapshot(ClientRoots::unsupported())
            .expect("root snapshot")
            .select(Some(&self.root))
            .expect("select workspace")
    }

    fn repair(&self) -> RepairService {
        RepairService::new(self.config.clone(), Arc::clone(&self.change))
    }

    async fn change(&self, request: ChangeRequest) -> ChangeOutcome {
        self.change
            .execute(request, &self.workspace(), CancellationToken::new(), None)
            .await
    }

    /// Creates a change, introduces the failure with the supplied patch, and
    /// requires a fresh FAIL row from `cargo check`.
    async fn park_failure(&self, patch: PatchInput) -> (String, String) {
        let created = self.change(create_request()).await;
        assert_eq!(created.status, "CREATED", "{created:#?}");
        let id = created.data.change_id.clone().expect("change id");
        let base = created.data.base_identity.clone().expect("base identity");
        let staged = self.change(stage_request(&id, 0, &base, vec![patch])).await;
        assert_eq!(staged.status, "STAGED", "{staged:#?}");
        let failed = self
            .change(validate_request(&id, 1, &base, GateTargetId::Check))
            .await;
        assert_eq!(failed.status, "FAIL", "{failed:#?}");
        (id, base)
    }

    async fn repair_execute(
        &self,
        request: RepairRequest,
    ) -> agz_rust_coder::repair::RepairOutcome {
        self.repair()
            .execute(request, &self.workspace(), CancellationToken::new(), None)
            .await
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        if let Some(base) = self.root.parent() {
            let _ = fs::remove_dir_all(base);
        }
    }
}

fn create_request() -> ChangeRequest {
    ChangeRequest {
        action: ChangeAction::Create,
        change_id: None,
        expected_revision: None,
        base_identity: None,
        patches: Vec::new(),
        new_files: Vec::new(),
        migration: None,
        target: GateTargetId::Check,
        options: ValidationOptions::default(),
        detail: GateDetail::Compact,
        timings: false,
    }
}

fn stage_request(id: &str, revision: u64, base: &str, patches: Vec<PatchInput>) -> ChangeRequest {
    ChangeRequest {
        action: ChangeAction::Stage,
        change_id: Some(id.to_owned()),
        expected_revision: Some(revision),
        base_identity: Some(base.to_owned()),
        patches,
        new_files: Vec::new(),
        migration: None,
        target: GateTargetId::Check,
        options: ValidationOptions::default(),
        detail: GateDetail::Compact,
        timings: false,
    }
}

fn validate_request(id: &str, revision: u64, base: &str, target: GateTargetId) -> ChangeRequest {
    ChangeRequest {
        action: ChangeAction::Validate,
        change_id: Some(id.to_owned()),
        expected_revision: Some(revision),
        base_identity: Some(base.to_owned()),
        patches: Vec::new(),
        new_files: Vec::new(),
        migration: None,
        target,
        options: ValidationOptions::default(),
        detail: GateDetail::Compact,
        timings: false,
    }
}

fn patch(file: &str, old: &str, new: &str) -> PatchInput {
    PatchInput {
        file: file.to_owned(),
        old_string: old.to_owned(),
        new_string: new.to_owned(),
    }
}

fn candidate(id: &str, patches: Vec<PatchInput>) -> RepairCandidateInput {
    RepairCandidateInput {
        id: Some(id.to_owned()),
        source: Some("host".to_owned()),
        patches,
    }
}

fn repair_request(action: RepairAction, id: &str) -> RepairRequest {
    RepairRequest {
        action,
        change_id: id.to_owned(),
        diagnostic_ids: Vec::new(),
        candidates: Vec::new(),
        test_target: None,
        budget: RepairBudget {
            max_candidates: 4,
            max_compiles: 4,
            wall_time_ms: 120_000,
        },
        reduction_scope: RepairReductionScope::default(),
        failure_predicate: None,
    }
}

fn digest(path: &Path) -> String {
    let bytes = fs::read(path).expect("read digest target");
    let mut hasher = Sha256::new();
    hasher.update(&bytes);
    format!("{:x}", hasher.finalize())
}

fn git_command(root: &Path, arguments: &[&str]) {
    let status = Command::new("git")
        .args(arguments)
        .current_dir(root)
        .status()
        .expect("run git fixture command");
    assert!(status.success(), "git command failed: {arguments:?}");
}

const BORROW_LIB: &[u8] = b"pub fn consume(value: String) -> usize {\n    value.len()\n}\n\npub fn run() -> usize {\n    let text = String::from(\"x\");\n    text.len()\n}\n";

fn borrow_failure_patch() -> PatchInput {
    patch(
        "src/lib.rs",
        "    let text = String::from(\"x\");\n    text.len()",
        "    let text = String::from(\"x\");\n    consume(text);\n    text.len()",
    )
}

#[tokio::test]
async fn borrow_move_analysis_is_source_backed_and_compare_prefers_behavior_preserving() {
    let fixture = Fixture::new("borrow", BORROW_LIB);
    let (id, _base) = fixture.park_failure(borrow_failure_patch()).await;
    let original = digest(&fixture.root.join("src/lib.rs"));

    let analyzed = fixture
        .repair_execute(repair_request(RepairAction::Analyze, &id))
        .await;
    assert_eq!(analyzed.status, "ANALYZED", "{analyzed:#?}");
    assert!(analyzed.data.usable);
    assert!(!analyzed.is_error);
    let analysis = analyzed.data.analysis.as_ref().expect("analysis");
    assert!(
        analysis
            .diagnostics
            .iter()
            .any(|group| group.codes.iter().any(|code| code == "E0382")),
        "{analysis:#?}"
    );
    let moved = analysis
        .ownership
        .iter()
        .find(|ownership| ownership.kind == "movedValue")
        .expect("moved value explanation");
    assert_eq!(moved.symbol.as_deref(), Some("text"));
    assert!(
        moved
            .source_evidence
            .iter()
            .any(|excerpt| excerpt.file == "src/lib.rs" && excerpt.text.contains("text")),
        "ownership evidence must quote real candidate source: {moved:#?}"
    );
    assert!(
        analysis
            .sources
            .iter()
            .any(|source| source.kind == "compilerSuggestion"),
        "{analysis:#?}"
    );
    assert!(
        !analyzed.data.candidates.is_empty(),
        "analysis must expose candidate sources"
    );

    let clone = candidate(
        "clone",
        vec![patch(
            "src/lib.rs",
            "consume(text);",
            "consume(text.clone());",
        )],
    );
    let borrow = candidate(
        "borrow",
        vec![
            patch(
                "src/lib.rs",
                "pub fn consume(value: String) -> usize {",
                "pub fn consume(value: &str) -> usize {",
            ),
            patch("src/lib.rs", "consume(text);", "consume(&text);"),
        ],
    );
    let mut request = repair_request(RepairAction::Compare, &id);
    request.candidates = vec![clone, borrow];
    let compared = fixture.repair_execute(request).await;
    assert_eq!(compared.status, "COMPARED", "{compared:#?}");
    assert!(!compared.is_error);
    let selected = compared
        .data
        .selected
        .as_ref()
        .unwrap_or_else(|| panic!("selected candidate: {compared:#?}"));
    assert_eq!(selected.id, "borrow");
    assert_eq!(selected.verification, "compileVerified");
    let clone_result = compared
        .data
        .candidates
        .iter()
        .find(|result| result.id == "clone")
        .expect("clone result");
    assert_eq!(clone_result.status, "measured");
    assert_eq!(clone_result.compile.as_deref(), Some("compiled"));
    assert!(
        clone_result
            .impacts
            .iter()
            .any(|impact| impact.kind == "unnecessaryClone"),
        "clone candidate must surface the performance impact: {clone_result:#?}"
    );
    assert!(
        compared
            .data
            .eliminated
            .iter()
            .any(|entry| entry.id == "clone" && entry.reason.contains("unnecessaryClone")),
        "{:#?}",
        compared.data.eliminated
    );
    assert_eq!(
        digest(&fixture.root.join("src/lib.rs")),
        original,
        "the original workspace must never be written"
    );
}

#[tokio::test]
async fn trait_bound_fixture_generates_compiling_candidate() {
    let source = b"#[derive(PartialEq)]\npub struct Config {\n    pub value: u8,\n}\n\npub fn show(config: &Config) -> String {\n    format!(\"{config}\")\n}\n";
    let fixture = Fixture::new("trait", source);
    let (id, _base) = fixture
        .park_failure(patch(
            "src/lib.rs",
            "    format!(\"{config}\")",
            "    format!(\"{config:?}\")",
        ))
        .await;

    let analyzed = fixture
        .repair_execute(repair_request(RepairAction::Analyze, &id))
        .await;
    assert_eq!(analyzed.status, "ANALYZED", "{analyzed:#?}");
    let analysis = analyzed.data.analysis.as_ref().expect("analysis");
    let obligation = analysis
        .ownership
        .iter()
        .find(|ownership| ownership.kind == "missingTraitBound")
        .expect("trait obligation explanation");
    assert_eq!(obligation.trait_name.as_deref(), Some("Debug"));
    assert_eq!(obligation.symbol.as_deref(), Some("Config"));

    let tried = fixture
        .repair_execute(repair_request(RepairAction::Try, &id))
        .await;
    assert_eq!(tried.status, "TRIED", "{tried:#?}");
    let measured = tried
        .data
        .candidates
        .iter()
        .filter(|result| result.status == "measured")
        .collect::<Vec<_>>();
    assert!(!measured.is_empty(), "{tried:#?}");
    assert!(
        measured
            .iter()
            .any(|result| result.compile.as_deref() == Some("compiled")
                && result
                    .delta
                    .as_ref()
                    .is_some_and(|delta| delta.before_errors > 0 && delta.after_errors == 0)),
        "a generated candidate must fix the trait-bound failure: {measured:#?}"
    );
}

#[tokio::test]
async fn missing_import_fixture_generates_compiling_candidate() {
    let source = b"use std::collections::HashMap;\n\npub fn run() -> usize {\n    let map: HashMap<String, u8> = HashMap::new();\n    map.len()\n}\n";
    let fixture = Fixture::new("import", source);
    let (id, _base) = fixture
        .park_failure(patch(
            "src/lib.rs",
            "use std::collections::HashMap;\n\npub fn run",
            "pub fn run",
        ))
        .await;

    let tried = fixture
        .repair_execute(repair_request(RepairAction::Try, &id))
        .await;
    assert_eq!(tried.status, "TRIED", "{tried:#?}");
    assert!(
        tried.data.candidates.iter().any(|result| {
            result.status == "measured"
                && result.compile.as_deref() == Some("compiled")
                && result
                    .delta
                    .as_ref()
                    .is_some_and(|delta| delta.fixed_codes.iter().any(|code| code == "E0433"))
        }),
        "an import candidate must compile and fix E0433: {:#?}",
        tried.data.candidates
    );
}

#[tokio::test]
async fn multipart_candidate_with_stale_part_is_rejected_as_a_whole() {
    let fixture = Fixture::new("multipart", BORROW_LIB);
    let (id, _base) = fixture.park_failure(borrow_failure_patch()).await;

    let multipart = candidate(
        "multipart",
        vec![
            patch("src/lib.rs", "consume(text);", "consume(text.clone());"),
            patch("src/lib.rs", "missing text", "replacement"),
        ],
    );
    let mut request = repair_request(RepairAction::Try, &id);
    request.candidates = vec![multipart];
    let tried = fixture.repair_execute(request).await;
    assert_eq!(tried.status, "TRIED", "{tried:#?}");
    let result = &tried.data.candidates[0];
    assert_eq!(result.status, "rejected", "{result:#?}");
    assert!(
        result.reason.contains("not applied as a whole"),
        "{}",
        result.reason
    );
    assert_eq!(result.compile, None);
    assert_eq!(
        tried
            .data
            .budget
            .as_ref()
            .map(|budget| budget.compiles_used),
        Some(0)
    );
    let change_id = result.change_id.as_deref().expect("candidate change id");
    let inspected = fixture
        .change(ChangeRequest {
            action: ChangeAction::Inspect,
            change_id: Some(change_id.to_owned()),
            ..create_request()
        })
        .await;
    assert_eq!(inspected.status, "INSPECTED");
    assert_eq!(inspected.data.state, "discarded", "{inspected:#?}");
}

#[tokio::test]
async fn identical_candidate_hash_is_never_retried() {
    let fixture = Fixture::new("duplicate", BORROW_LIB);
    let (id, _base) = fixture.park_failure(borrow_failure_patch()).await;

    let first = candidate(
        "first",
        vec![patch(
            "src/lib.rs",
            "consume(text);",
            "consume(text.clone());",
        )],
    );
    let second = candidate(
        "second",
        vec![patch(
            "src/lib.rs",
            "consume(text);",
            "consume(text.clone());",
        )],
    );
    let mut request = repair_request(RepairAction::Try, &id);
    request.candidates = vec![first, second];
    let tried = fixture.repair_execute(request).await;
    assert_eq!(tried.status, "TRIED", "{tried:#?}");
    let measured = tried
        .data
        .candidates
        .iter()
        .filter(|result| result.status == "measured")
        .count();
    assert_eq!(measured, 1, "{:#?}", tried.data.candidates);
    assert_eq!(
        tried
            .data
            .candidates
            .iter()
            .filter(|result| result.status == "duplicate")
            .count(),
        1
    );
    assert_eq!(
        tried
            .data
            .budget
            .as_ref()
            .map(|budget| budget.compiles_used),
        Some(1)
    );
}

#[tokio::test]
async fn test_breaking_candidate_never_outranks_behavior_preserving() {
    let source = b"pub fn value() -> u8 {\n    2\n}\n\n#[cfg(test)]\nmod tests {\n    use super::*;\n\n    #[test]\n    fn keeps_two() {\n        assert_eq!(value(), 2);\n    }\n}\n";
    let fixture = Fixture::new("testgate", source);
    let (id, _base) = fixture
        .park_failure(patch(
            "src/lib.rs",
            "pub fn value() -> u8 {\n    2\n}",
            "pub fn value() -> u8 {\n    \"two\"\n}",
        ))
        .await;

    let breaker = candidate("breaker", vec![patch("src/lib.rs", "    \"two\"", "    3")]);
    let behavior = candidate(
        "behavior",
        vec![patch("src/lib.rs", "    \"two\"", "    2")],
    );
    let mut request = repair_request(RepairAction::Compare, &id);
    request.candidates = vec![breaker, behavior];
    request.test_target = Some(GateTargetId::Test);
    let compared = fixture.repair_execute(request).await;
    assert_eq!(compared.status, "COMPARED", "{compared:#?}");
    let selected = compared.data.selected.as_ref().expect("selected candidate");
    assert_eq!(selected.id, "behavior");
    assert_eq!(selected.verification, "testVerified");
    let breaker = compared
        .data
        .candidates
        .iter()
        .find(|result| result.id == "breaker")
        .expect("breaker result");
    assert_eq!(breaker.compile.as_deref(), Some("compiled"));
    assert_eq!(
        breaker.gate.as_ref().and_then(|gate| gate.tests_executed),
        Some(1)
    );
    assert!(
        compared
            .data
            .eliminated
            .iter()
            .any(|entry| { entry.id == "breaker" && entry.reason.contains("test gate") }),
        "{:#?}",
        compared.data.eliminated
    );
}

#[tokio::test]
async fn cancelled_repair_publishes_no_evidence() {
    let fixture = Fixture::new("cancel", BORROW_LIB);
    fixture
        .change
        .execute(
            create_request(),
            &fixture.workspace(),
            CancellationToken::new(),
            None,
        )
        .await;
    let cancellation = CancellationToken::new();
    cancellation.cancel();
    let outcome = fixture
        .repair()
        .execute(
            repair_request(RepairAction::Analyze, "ch-cancelled"),
            &fixture.workspace(),
            cancellation,
            None,
        )
        .await;
    assert_eq!(outcome.status, "CANCELLED", "{outcome:#?}");
    assert!(outcome.is_error);
    assert!(!outcome.data.usable);
    assert!(outcome.data.candidates.is_empty());
    assert!(outcome.data.analysis.is_none());
    assert_eq!(outcome.data.stop_reason, "cancelled");
}

#[tokio::test]
async fn effective_budget_only_narrows_the_configured_caps() {
    let fixture = Fixture::new("budget", BORROW_LIB);
    let service = fixture.repair();
    let budget = service.effective_budget(&RepairBudgetInput {
        max_candidates: Some(32),
        max_compiles: Some(1),
        wall_time_ms: Some(1_000),
    });
    assert_eq!(budget.max_candidates, fixture.config.repair.max_candidates);
    assert_eq!(budget.max_compiles, 1);
    assert_eq!(budget.wall_time_ms, 1_000);
    let widened = service.effective_budget(&RepairBudgetInput {
        max_candidates: Some(1),
        max_compiles: None,
        wall_time_ms: None,
    });
    assert_eq!(widened.max_candidates, 1);
    assert_eq!(widened.max_compiles, fixture.config.repair.max_compiles);

    let minimize = service.effective_minimize_budget(&RepairBudgetInput {
        max_candidates: Some(4),
        max_compiles: Some(32),
        wall_time_ms: Some(1_000),
    });
    assert_eq!(minimize.max_candidates, 4);
    assert_eq!(
        minimize.max_compiles,
        fixture.config.repair.minimize_max_compiles
    );
    assert_eq!(minimize.wall_time_ms, 1_000);
}

#[tokio::test]
async fn git_workspace_failure_evidence_replays_without_touching_originals() {
    let fixture = Fixture::new("git", BORROW_LIB);
    git_command(&fixture.root, &["init", "--quiet"]);
    git_command(
        &fixture.root,
        &["config", "user.email", "repair@example.invalid"],
    );
    git_command(&fixture.root, &["config", "user.name", "Repair Fixture"]);
    git_command(&fixture.root, &["add", "."]);
    git_command(&fixture.root, &["commit", "--quiet", "-m", "fixture"]);
    let tracked = digest(&fixture.root.join("src/lib.rs"));
    let (id, _base) = fixture.park_failure(borrow_failure_patch()).await;
    let tried = fixture
        .repair_execute(repair_request(RepairAction::Try, &id))
        .await;
    assert_eq!(tried.status, "TRIED", "{tried:#?}");
    assert!(tried.data.usable, "{tried:#?}");
    assert_eq!(digest(&fixture.root.join("src/lib.rs")), tracked);
    assert!(
        !fixture.root.join("target").exists(),
        "repair must not build in the original workspace"
    );
}
