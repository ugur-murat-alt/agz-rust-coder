#[tokio::test]
async fn policy_and_missing_tools_fail_closed() {
    let fixture = Fixture::new("policy", b"pub fn value() -> u8 { 1 }\n", |_| {});

    // A candidate outside the declared scope is refused before any change
    // scratch is created.
    let mut scoped = intent();
    scoped.scope_paths = vec!["src/lib.rs".to_owned()];
    let blocked = fixture
        .execute(start_request(
            scoped,
            vec![patch(
                "Cargo.toml",
                "edition = \"2024\"",
                "edition = \"2021\"",
            )],
            budget(2, 1),
        ))
        .await;
    assert_eq!(blocked.status, "BLOCKED", "{blocked:#?}");
    assert!(blocked.is_error);
    assert!(blocked.data.change_id.is_none());
    assert!(
        blocked.data.reason.contains("scopePaths"),
        "{}",
        blocked.data.reason
    );

    // A disabled required tool is a policy block, not a silent plan change.
    let mut config = fixture.config.clone();
    config.tools.docs = false;
    let work = WorkService::new(&config, Some(Arc::clone(&fixture.change)));
    let mut request = start_request(intent(), Vec::new(), budget(2, 1));
    request.constraints.required_tools = vec![WorkTool::Docs];
    let blocked = work
        .execute(
            request,
            &fixture.workspace(),
            CancellationToken::new(),
            None,
        )
        .await;
    assert_eq!(blocked.status, "BLOCKED", "{blocked:#?}");
    assert!(
        blocked.data.reason.contains("'docs'"),
        "{}",
        blocked.data.reason
    );

    // Offline work may not require a network-backed tool.
    let mut request = start_request(intent(), Vec::new(), budget(2, 1));
    request.constraints.offline = true;
    request.constraints.required_tools = vec![WorkTool::Docs];
    let blocked = fixture.execute(request).await;
    assert_eq!(blocked.status, "BLOCKED", "{blocked:#?}");
    assert!(
        blocked.data.reason.contains("offline"),
        "{}",
        blocked.data.reason
    );

    // Without the change tool the executor fails closed instead of inventing a
    // different candidate mechanism.
    let without_change = WorkService::new(&fixture.config, None);
    let blocked = without_change
        .execute(
            start_request(intent(), Vec::new(), budget(1, 0)),
            &fixture.workspace(),
            CancellationToken::new(),
            None,
        )
        .await;
    assert_eq!(blocked.status, "BLOCKED", "{blocked:#?}");
    assert!(
        blocked.data.reason.contains("'change'"),
        "{}",
        blocked.data.reason
    );
}

#[tokio::test]
async fn cancel_propagates_to_an_in_flight_validation() {
    let fixture = Fixture::new("cancel", b"pub fn value() -> u8 { 1 }\n", |_| {});
    let start = fixture
        .execute(start_request(
            intent(),
            vec![patch(
                "src/lib.rs",
                "pub fn value() -> u8 { 1 }",
                BAD_CANDIDATE,
            )],
            budget(3, 2),
        ))
        .await;
    assert_eq!(start.status, "NEEDS_MODEL", "{start:#?}");
    let work_id = start.data.work_id.clone().expect("work id");
    let token = start
        .data
        .handoff
        .clone()
        .expect("handoff")
        .continuation_token;

    let guard = Arc::clone(&fixture.guard);
    let work = Arc::clone(&fixture.work);
    let root = fixture.root.clone();
    let resume_work_id = work_id.clone();
    let resume = tokio::spawn(async move {
        let workspace = workspace_of(&guard, &root);
        work.execute(
            resume_request(
                &resume_work_id,
                &token,
                vec![patch("src/lib.rs", BAD_CANDIDATE, FIXED_CANDIDATE)],
            ),
            &workspace,
            CancellationToken::new(),
            None,
        )
        .await
    });

    // Wait until the record is published as validating, then cancel while the
    // bound Cargo check is still running.
    let workspace = fixture.workspace();
    let mut observed = false;
    for _ in 0..800 {
        let inspected = fixture
            .work
            .execute(
                inspect_request(&work_id),
                &workspace,
                CancellationToken::new(),
                None,
            )
            .await;
        if inspected.status == "INSPECTED" && inspected.data.state == "validating" {
            observed = true;
            break;
        }
        tokio::time::sleep(Duration::from_millis(5)).await;
    }
    assert!(observed, "the validating state was never observed");

    let cancelled = fixture.execute(cancel_request(&work_id)).await;
    assert_eq!(cancelled.status, "CANCELLED", "{cancelled:#?}");
    assert!(!cancelled.is_error);
    assert_eq!(cancelled.data.state, "cancelled");

    let resumed = resume.await.expect("resume task runs");
    assert_eq!(resumed.status, "CANCELLED", "{resumed:#?}");
    assert!(resumed.is_error);
    assert_eq!(resumed.data.state, "cancelled");

    let after = fixture
        .execute(resume_request(
            &work_id,
            "0".repeat(64).as_str(),
            vec![patch("src/lib.rs", FIXED_CANDIDATE, FIXED_CANDIDATE)],
        ))
        .await;
    assert_eq!(after.status, "STALE", "{after:#?}");
}

#[test]
fn work_input_rejects_unknown_fields_and_shell_commands() {
    let valid = serde_json::json!({
        "action": "resume",
        "workId": "wk-1-1-1",
        "continuationToken": "token",
        "patches": [{"file": "src/lib.rs", "oldString": "a", "newString": "b"}],
    });
    assert!(serde_json::from_value::<WorkInput>(valid.clone()).is_ok());

    let mut smuggled = valid.clone();
    smuggled["command"] = serde_json::json!("rm -rf /");
    assert!(
        serde_json::from_value::<WorkInput>(smuggled).is_err(),
        "work has no arbitrary command surface"
    );

    let mut nested = valid;
    nested["patches"][0]["command"] = serde_json::json!("sh -c true");
    assert!(
        serde_json::from_value::<WorkInput>(nested).is_err(),
        "candidate patches have no command surface"
    );
}
