#[tokio::test]
async fn inactive_feature_fails_and_then_compiles_when_selected() {
    let fixture = Fixture::new("feature");
    let snippet = "let _ = dep::extra(1);".to_owned();

    let failed = fixture
        .probe(
            vec![snippet.clone()],
            None,
            Vec::new(),
            "src/lib.rs",
            CancellationToken::new(),
        )
        .await;
    assert_eq!(probe_status(&failed), "COMPILE_FAILED", "{failed:#?}");
    let probe = failed.probe.expect("probe payload");
    assert!(
        probe
            .proposals
            .iter()
            .any(|proposal| proposal.kind == "feature"
                && proposal.name == "dep/extra"
                && proposal.requires_explicit_host_change),
        "an inactive feature must surface as a proposal: {probe:#?}"
    );

    let selected = fixture
        .probe(
            vec![snippet],
            None,
            vec!["dep/extra".to_owned()],
            "src/lib.rs",
            CancellationToken::new(),
        )
        .await;
    assert_eq!(
        probe_status(&selected),
        "COMPILES_IN_CONFIGURATION",
        "{selected:#?}"
    );
    let probe = selected.probe.expect("probe payload");
    assert_eq!(probe.configuration.features, vec!["dep/extra".to_owned()]);
    assert!(
        probe.compile.command.contains("--features dep/extra"),
        "{}",
        probe.compile.command
    );
}

