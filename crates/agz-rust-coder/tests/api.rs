#[tokio::test]
async fn budgets_and_cancellation_are_enforced() {
    let mut fixture = Fixture::new("budgets");
    fixture.config.api.max_snippets = 1;
    let data = fixture
        .probe(
            vec!["let _ = 1;".to_owned(), "let _ = 2;".to_owned()],
            None,
            Vec::new(),
            "src/lib.rs",
            CancellationToken::new(),
        )
        .await;
    assert_eq!(data.status, "INVALID", "{data:#?}");
    assert!(data.reason.contains("at most 1"));

    let cancelled = CancellationToken::new();
    cancelled.cancel();
    let data = fixture
        .probe(
            vec!["let _ = 1;".to_owned()],
            None,
            Vec::new(),
            "src/lib.rs",
            cancelled,
        )
        .await;
    assert_eq!(data.status, "CANCELLED", "{data:#?}");
}
