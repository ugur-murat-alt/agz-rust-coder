#[tokio::test]
async fn expected_signature_is_asserted_and_harness_is_reported() {
    let fixture = Fixture::new("expected");
    let lock = digest(&fixture.root.join("Cargo.lock"));

    let passed = fixture
        .probe(
            vec!["crate::value()".to_owned()],
            Some("u8".to_owned()),
            Vec::new(),
            "src/lib.rs",
            CancellationToken::new(),
        )
        .await;
    assert_eq!(
        probe_status(&passed),
        "COMPILES_IN_CONFIGURATION",
        "{passed:#?}"
    );
    let probe = passed.probe.expect("probe payload");
    assert_eq!(probe.assertion, "expected-type-return");
    assert!(probe.implementation_complete);
    assert_eq!(probe.harness.len(), 2);
    assert!(probe.harness.iter().any(|file| file.kind == "patched"));
    assert!(probe.harness.iter().any(|file| file.kind == "created"));
    assert_eq!(probe.input_hash.len(), 64);
    assert!(
        probe
            .input_hash
            .chars()
            .all(|character| character.is_ascii_hexdigit())
    );
    assert_eq!(probe.budget.max_snippets, fixture.config.api.max_snippets);
    assert_eq!(
        probe.budget.compile_timeout_ms,
        fixture.config.api.compile_timeout_ms
    );
    assert!(probe.original_unchanged);
    assert_eq!(digest(&fixture.root.join("Cargo.lock")), lock);

    let failed = fixture
        .probe(
            vec!["crate::value()".to_owned()],
            Some("String".to_owned()),
            Vec::new(),
            "src/lib.rs",
            CancellationToken::new(),
        )
        .await;
    assert_eq!(probe_status(&failed), "COMPILE_FAILED", "{failed:#?}");
    let probe = failed.probe.expect("probe payload");
    assert!(
        probe
            .diagnostics
            .iter()
            .any(|diagnostic| diagnostic.code.as_deref() == Some("E0308")),
        "the expected type must be unified by the compiler: {probe:#?}"
    );
}

